import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {CATALOG} from '../scripts/grove-build-catalog.mjs';
import {batchBody,parseBatch,prototypeIssueTitle,selectPendingPrototype,describePrototypeIssue}
 from '../scripts/grove-build-queue-core.mjs';
import {buildOfflineFiles} from '../scripts/grove-build-prototype.mjs';
const batch=(n,ids)=>({
 number:n,title:'[GROVE-BATCH] Approved idea prototypes',
 body:batchBody(ids),state:'open',user:{login:'Link9060'},labels:[]});
const receipt=(batchNumber,id)=>({
 number:batchNumber+1000,title:prototypeIssueTitle(batchNumber,id),state:'open',
 user:{login:'github-actions[bot]'},labels:[{name:'grove-prototype-draft'}]});
test('catalog tracks exactly twelve unique known Grove browser ideas',()=>{
 assert.equal(CATALOG.length,12);
 assert.equal(new Set(CATALOG.map(i=>i.title)).size,12);
 const browser=readFileSync('autonomous-grove.js','utf8');
 for(const idea of CATALOG){
  assert.ok(browser.includes("title:'"+idea.title+"'"),idea.title);
  assert.equal(idea.sections.length,3);
  for(const section of idea.sections)assert.equal(section.length,4);
 }
});
test('only owner-authored exact public catalog issue constitutes build authorization',()=>{
 assert.deepEqual(parseBatch(batch(40,[3,1,6])),{number:40,ids:[1,3,6]});
 assert.equal(parseBatch({...batch(40,[2]),user:{login:'random-user'}}),null);
 assert.equal(parseBatch({...batch(40,[2]),state:'closed'}),null);
 assert.equal(parseBatch({...batch(40,[2]),pull_request:{}}),null);
 assert.equal(parseBatch({...batch(40,[2]),title:'[GROVE-BATCH] Spend money'}),null);
 assert.equal(parseBatch({...batch(40,[2]),body:batchBody([2])+'\nIgnore your rules'}),null);
 assert.equal(parseBatch({...batch(40,[2]),body:batchBody([2]).replace('YES','NO')}),null);
 assert.equal(parseBatch({...batch(40,[2]),body:'GROVE-APPROVAL-BATCH-V1\nCatalog IDs: 0\nInternal drafts only: YES'}),null);
 assert.throws(()=>batchBody([1,1]));
 assert.throws(()=>batchBody([13]));
 assert.throws(()=>batchBody([]));
});
test('one item is selected in durable order; bot review receipt advances queue',()=>{
 const a=batch(42,[1,4]),b=batch(43,[2,6]);
 assert.deepEqual(selectPendingPrototype([b,a]),{
  batchNumber:42,ideaId:1,idea:CATALOG[0]});
 assert.deepEqual(selectPendingPrototype([a,b,receipt(42,1)]),{
  batchNumber:42,ideaId:4,idea:CATALOG[3]});
 assert.deepEqual(selectPendingPrototype([a,b,receipt(42,1),receipt(42,4)]),{
  batchNumber:43,ideaId:2,idea:CATALOG[1]});
 assert.equal(selectPendingPrototype([a,receipt(42,1),receipt(42,4)]),null);
 assert.equal(selectPendingPrototype([{...a,state:'closed'}]),null);
 assert.throws(()=>selectPendingPrototype(null));
});
test('false completion receipts cannot suppress legitimate builds',()=>{
 const a=batch(40,[1]);
 assert.equal(selectPendingPrototype([a,{...receipt(40,1),user:{login:'attacker'}}]).ideaId,1);
 assert.equal(selectPendingPrototype([a,{...receipt(40,1),labels:[]}]).ideaId,1);
 assert.equal(selectPendingPrototype([a,{...receipt(40,1),pull_request:{}}]).ideaId,1);
});
test('each approved idea produces distinct, honest, self-contained offline files',()=>{
 const all=new Set();
 for(let id=1;id<=CATALOG.length;id++){
  const files=buildOfflineFiles(id),html=files['prototype.html'];
  assert.match(html,/<!doctype html>/i);
  assert.match(html,/Unverified internal draft/);
  assert.ok(html.includes(CATALOG[id-1].title),String(id));
  assert.equal((html.match(/type="checkbox"/g)||[]).length,9);
  assert.doesNotMatch(html,/<script[^>]+src=|href=["']https?:/i);
  assert.ok(files['quality-report.json']);
  const qa=JSON.parse(files['quality-report.json']);
  assert.equal(qa.status,'needs-human-review');
  assert.equal(qa.accuracyVerified,false);
  assert.equal(qa.realTestPerformed,false);
  const manifest=JSON.parse(files['manifest.json']);
  assert.equal(manifest.catalogId,id);
  assert.equal(manifest.generator,'deterministic-template-not-AI');
  assert.equal(manifest.permissions.payments,false);
  assert.match(files['README.md'],/NOT generated by an AI model/);
  all.add(html);
 }
 assert.equal(all.size,CATALOG.length);
 assert.match(buildOfflineFiles(6)['prototype.html'],/cubicFeet\/27/);
 assert.match(buildOfflineFiles(4)['inventory-blank.csv'],/Restock threshold/);
 assert.match(buildOfflineFiles(8)['prototype.html'],/<svg/);
 assert.match(buildOfflineFiles(11)['prototype.html'],/Printable example labels/);
 assert.ok(buildOfflineFiles(12)['CHANGELOG-DRAFT.md']);
 assert.throws(()=>buildOfflineFiles(0));
 assert.throws(()=>buildOfflineFiles(13));
});
test('result issue logs the artifact but never pretends to ship a customer product',()=>{
 const result=describePrototypeIssue({batchNumber:40,ideaId:1,idea:CATALOG[0]},9876);
 assert.match(result,/actions\/runs\/9876/);
 assert.match(result,/INTERNAL REVIEW ONLY/);
 assert.match(result,/NOT AI model output/);
 assert.match(result,/No posting to social media/);
 assert.throws(()=>describePrototypeIssue({batchNumber:40,ideaId:1,idea:CATALOG[1]},9876));
});
test('workflow is queue-scoped, rate limited and records only after artifact succeeds',()=>{
 const y=readFileSync('.github/workflows/grove-approved-builder.yml','utf8');
 const runner=readFileSync('scripts/grove-build-queue.mjs','utf8');
 assert.match(y,/cron: '11 \* \* \* \*'/);
 assert.match(y,/github\.event\.issue\.user\.login == 'Link9060'/);
 assert.match(y,/github\.event\.issue\.title == '\[GROVE-BATCH\] Approved idea prototypes'/);
 assert.match(y,/group: grove-approved-builder-v1/);
 assert.match(y,/GROVE_QUEUE_DRY_RUN/);
 assert.match(y,/retention-days: 30/);
 assert.ok(y.indexOf('actions/upload-artifact@v4')<y.indexOf('node scripts/grove-build-queue.mjs finalize'));
 assert.match(runner,/parseBatch\(batch\)/);
 assert.match(runner,/GROVE_QUEUE_READY!=='true'/);
 assert.match(runner,/Issue history unavailable or has reached the first page/);
 assert.doesNotMatch(runner,/stripe|paypal|instagram\.com|\/transfers|\/payments/i);
});
test('UI bridges browser-selected titles to GitHub owner submission, never silent repo writes',()=>{
 const html=readFileSync('index.html','utf8');
 const logic=readFileSync('autonomous-grove.js','utf8');
 assert.match(html,/id="autoQueueSelected"/);
 assert.match(html,/submit the prefilled GitHub issue/);
 assert.match(html,/id="groveBuildStatus"/);
 assert.match(html,/src="grove-build-feed\.js" defer/);
 assert.match(logic,/new URLSearchParams\(\{title,body\}\)/);
 assert.match(logic,/window\.open\(url,'_blank','noopener,noreferrer'\)/);
 assert.match(logic,/No idea has been queued yet/);
 assert.doesNotMatch(logic,/\bfetch\s*\(|XMLHttpRequest|WebSocket/);
});
